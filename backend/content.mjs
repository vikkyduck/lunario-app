/* ── Сборка: файл из ../content, если он есть; иначе запасное значение выше ── */
function build() {
  const r = {};

  const arcana = rows('карты-таро.txt', 3);
  r.ARCANA = arcana ? arcana.map((c) => [c[0], c[1], c[2]]) : ARCANA_FALLBACK;

  /* У знаков из файла берём только черту: даты определяют знак и меняться не должны. */
  const signs = rows('знаки-зодиака.txt', 2);
  r.SIGNS = SIGNS_FALLBACK.map((s, i) => (signs && signs[i] ? [signs[i][0], s[1], signs[i][1]] : s));

  const tones = rows('тона-дня.txt', 3);
  r.DAY_TONES = tones ? tones.map((c) => {
    const [w, l, hh, m] = String(c[2]).split(',');
    return [c[0], c[1], { work: num(w, 60), love: num(l, 60), health: num(hh, 60), money: num(m, 60) }];
  }) : DAY_TONES_FALLBACK;

  /* Рисунок руны привязан к порядку строк — он остаётся в коде. */
  const runes = rows('руны.txt', 3);
  r.RUNES = runes
    ? runes.map((c, i) => [c[0], c[1], (RUNES_FALLBACK[i] || RUNES_FALLBACK[0])[2], c[2]])
    : RUNES_FALLBACK;

  const dest = rows('нумерология-судьба.txt', 3);
  r.NUM_DESTINY = dest ? Object.fromEntries(dest.map((c) => [c[0], [c[1], c[2]]])) : NUM_DESTINY_FALLBACK;

  const year = rows('нумерология-год.txt', 2);
  r.NUM_YEAR = year ? Object.fromEntries(year.map((c) => [c[0], c[1]])) : NUM_YEAR_FALLBACK;

  const nday = rows('нумерология-день.txt', 2);
  r.NUM_DAY = nday ? Object.fromEntries(nday.map((c) => [c[0], c[1]])) : NUM_DAY_FALLBACK;

  r.AFFIRMATIONS = lines('аффирмации.txt') || AFFIRMATIONS_FALLBACK;
  r.DAY_QUESTIONS = lines('вопросы-дня.txt') || DAY_QUESTIONS_FALLBACK;

  const yn = rows('ответы-да-нет.txt', 4);
  r.YN_RIDERS = yn ? Object.fromEntries(yn.map((c) => [c[0], [c[1], c[2], c[3]]])) : YN_RIDERS_FALLBACK;

  r.YN_VERDICTS = YN_VERDICTS_FALLBACK;
  r.TOPICS = TOPICS_FALLBACK;
  return r;
}

