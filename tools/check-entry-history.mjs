import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {entryPage} from '../backend/entries.mjs';
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE entries(id INTEGER PRIMARY KEY,user_id INTEGER,day TEXT,kind TEXT,question TEXT,title TEXT,body TEXT,data TEXT)');
const add=db.prepare('INSERT INTO entries(user_id,day,kind,question,title,body,data) VALUES(?,?,?,?,?,?,?)');
for(let i=0;i<105;i++)add.run(1,'2026-09-14','yesno','private:Вопрос '+i,'Да','Ответ','');
for(let i=0;i<110;i++)add.run(1,'2026-09-15','card','','Карта','','{}');
const foreign=add.run(2,'2026-09-15','yesno','private:Чужой вопрос','Нет','','{}').lastInsertRowid;
const get=q=>entryPage(db,1,new URLSearchParams(q),s=>String(s||'').replace(/^private:/,''));
const first=get({kind:'questions'});
assert.equal(first.items.length,100);assert.ok(first.items.every(x=>x.kind==='yesno'&&x.question.startsWith('Вопрос')));
assert.ok(first.next);const older=get({kind:'questions',before:String(first.next)});
assert.equal(older.items.length,5);assert.equal(older.next,null);
assert.equal(new Set([...first.items,...older.items].map(x=>x.id)).size,105);
assert.ok(get({kind:'card'}).items.every(x=>x.kind==='card'));
assert.equal(get({id:String(foreign)}).items.length,0);
assert.equal(get({id:String(older.items[0].id)}).items[0].question,older.items[0].question);
assert.equal(get({}).items.length,100);
db.close();console.log('PASS: questions remain reachable behind 110 newer cards; paging, original text and account isolation.');
